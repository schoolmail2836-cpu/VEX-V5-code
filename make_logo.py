"""Turn the ICT Robotics logo SVG into drawing data for the V5 Brain screen.

Usage: python3 make_logo.py ict-robotics-red.svg [height_px]
Needs: pip install cairosvg pillow numpy

Writes:
  logo_data.py - paste it into override_robot.py, replacing the
                 "Startup logo data" section
  preview.png  - what the Brain will show (480 x 240, scaled 2x)

The V5 screen can't load an SVG and has no fill for odd shapes, so the
logo is rasterized and stored as horizontal line runs (y, start x, end x),
one list per colour. The robot draws each run with draw_line.
"""
import io
import sys

import cairosvg
import numpy as np
from PIL import Image

SCREEN_W, SCREEN_H = 480, 240
LOGO_TOP = 12 # pixels from the top of the screen

svg_path = sys.argv[1]
height = int(sys.argv[2]) if len(sys.argv) > 2 else 190

# The dark-ink ICT is invisible on the black screen, so draw it white
# (same as the red-on-dark variant).
svg = open(svg_path).read().replace('fill="#111214"', 'fill="#ffffff"')
png = cairosvg.svg2png(bytestring=svg.encode(), output_height=height)
image = Image.open(io.BytesIO(png)).convert("RGBA")
pixels = np.asarray(image).astype(float)
rgb = pixels[..., :3] * (pixels[..., 3:4] / 255) # composite over black
r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]

# 0 = background, 1 = white, 2 = red.
# Grey edge pixels go white or background by brightness and reddish ones
# go red, so the white letters don't get red fringes.
grey = g > 0.45 * r
index = np.where(grey, np.where((r + g + b) / 3 > 120, 1, 0), np.where(r > 70, 2, 0))

logo_h, logo_w = index.shape
runs = {1: [], 2: []}
for y in range(logo_h):
    row = index[y]
    x = 0
    while x < logo_w:
        colour = row[x]
        start = x
        while x < logo_w and row[x] == colour:
            x += 1
        if colour:
            runs[colour].extend((y, start, x - 1))


def tuple_text(name, values):
    lines = []
    for i in range(0, len(values), 24):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + 24]) + ",")
    return name + " = (\n" + "\n".join(lines) + "\n)\n"


logo_x = (SCREEN_W - logo_w) // 2
with open("logo_data.py", "w") as out:
    out.write("# ----------------------------------------------------------------------\n")
    out.write("# Startup logo data\n")
    out.write("# Generated by make_logo.py from the ICT Robotics logo, don't edit by hand.\n")
    out.write("# Each run is three numbers: y, start x, end x (in logo pixels).\n")
    out.write("# ----------------------------------------------------------------------\n\n")
    out.write("LOGO_W = %d\nLOGO_H = %d\n" % (logo_w, logo_h))
    out.write("LOGO_X = %d # centred on the 480 px wide screen\n" % logo_x)
    out.write("LOGO_Y = %d\n" % LOGO_TOP)
    out.write(tuple_text("LOGO_WHITE", runs[1]))
    out.write(tuple_text("LOGO_RED", runs[2]))

# Preview of exactly what the robot draws
colours = {1: (255, 255, 255), 2: (152, 0, 0)}
screen = Image.new("RGB", (SCREEN_W, SCREEN_H))
dots = screen.load()
for colour, values in runs.items():
    for i in range(0, len(values), 3):
        y, x0, x1 = values[i:i + 3]
        for x in range(x0, x1 + 1):
            dots[logo_x + x, LOGO_TOP + y] = colours[colour]
screen.resize((SCREEN_W * 2, SCREEN_H * 2), Image.NEAREST).save("preview.png")

print("logo %d x %d px, %d white runs, %d red runs"
      % (logo_w, logo_h, len(runs[1]) // 3, len(runs[2]) // 3))
